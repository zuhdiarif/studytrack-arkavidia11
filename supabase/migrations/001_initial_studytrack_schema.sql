CREATE TABLE IF NOT EXISTS public.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.courses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  kode TEXT NOT NULL DEFAULT '',
  dosen TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
  mata_kuliah_id INTEGER NOT NULL REFERENCES public.courses (id) ON DELETE CASCADE,
  judul TEXT NOT NULL,
  deskripsi TEXT NOT NULL DEFAULT '',
  deadline TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  status TEXT NOT NULL DEFAULT 'belum' CHECK (status IN ('belum', 'selesai')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
  ON public.users (LOWER(email));

CREATE INDEX IF NOT EXISTS idx_courses_user_id
  ON public.courses (user_id);

CREATE INDEX IF NOT EXISTS idx_tugas_mk_deadline
  ON public.tasks (mata_kuliah_id, deadline);

CREATE INDEX IF NOT EXISTS idx_tasks_user_deadline
  ON public.tasks (user_id, deadline);

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.courses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS users_self_isolation ON public.users;
CREATE POLICY users_self_isolation ON public.users
  FOR ALL
  USING (id = NULLIF(current_setting('app.current_user_id', true), '')::INTEGER)
  WITH CHECK (id = NULLIF(current_setting('app.current_user_id', true), '')::INTEGER);

DROP POLICY IF EXISTS courses_tenant_isolation ON public.courses;
CREATE POLICY courses_tenant_isolation ON public.courses
  FOR ALL
  USING (user_id = NULLIF(current_setting('app.current_user_id', true), '')::INTEGER)
  WITH CHECK (user_id = NULLIF(current_setting('app.current_user_id', true), '')::INTEGER);

DROP POLICY IF EXISTS tasks_tenant_isolation ON public.tasks;
CREATE POLICY tasks_tenant_isolation ON public.tasks
  FOR ALL
  USING (user_id = NULLIF(current_setting('app.current_user_id', true), '')::INTEGER)
  WITH CHECK (user_id = NULLIF(current_setting('app.current_user_id', true), '')::INTEGER);

